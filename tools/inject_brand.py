"""Replace the portfolio's displayed site name with "Fengmei" everywhere.

Covers SSR pages, Nuxt payloads, both client bundles, SEO/JSON-LD metadata,
GraphQL/lLMS/Markdown copies and the recorded HTML snapshots, so a later
rebuild with inject_all_data.py / inject_all_html.py cannot bring the old
name back. Idempotent: re-running reports zero changes.

URLs and account handles are intentionally NOT touched (they are addresses,
not the displayed name): jesperlandberg.com, instagram/jesperlandberg222,
x.com/jesper_alpacka, linkedin .../jesper-landberg-..., jesper@alpacka.studio.

Run from the mirror root:
    python3 tools/inject_brand.py
    python3 tools/inject_all_data.py && python3 tools/inject_all_html.py
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from project_config import ROOT

os.chdir(ROOT)
BRAND = "Fengmei"

# Order matters: the full name first, then the remaining bare first/last name
# (e.g. "Jesper is normally the lead or only developer" in llms.txt/EH).
RULES = [
    (re.compile(r"Jesper\s+Landberg", re.I), BRAND),
    (re.compile(r"\bJesper\b"), BRAND),
    (re.compile(r"\bLandberg\b"), BRAND),
]

SKIP_DIRS = {"screenshots", "node_modules", ".git", ".workbuddy", "assets"}
# These two contain the search patterns themselves.
SKIP_FILES = {"tools/inject_brand.py", "tools/verify_brand.js"}
TEXT_EXT = {".html", ".htm", ".js", ".mjs", ".css", ".json", ".md", ".txt",
            ".xml", ".py", ".bin", ".sh", ".yml", ".yaml", ".map"}

CSS_BEGIN = "/* === brand name — generated by tools/inject_brand.py ==="
CSS_END = "/* === end brand name === */"
CSS = CSS_BEGIN + """
/* Keep the site name exactly as authored (Fengmei) instead of the stock
 * .label{text-transform:uppercase}. The WebGL text renderer reads the CSS
 * text-transform when it bakes its glyph mesh, so this keeps the WebGL name
 * and the DOM text in sync. Only the HUD home link is affected; every other
 * label (PROFILE / CLOSE / NEWSLETTER / social links) keeps its styling. */
div.fixed.inset-0.z-40 a.label[href="/"] {
  text-transform: none !important;
}
""" + CSS_END


def apply(t):
    n = 0
    for pat, rep in RULES:
        t, k = pat.subn(rep, t)
        n += k
    return t, n


def walk():
    for root, dirs, files in os.walk("."):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for f in files:
            fp = os.path.relpath(os.path.join(root, f), ".")
            if fp in SKIP_FILES or os.path.splitext(f)[1].lower() not in TEXT_EXT:
                continue
            yield fp


changed, total = 0, 0
for fp in walk():
    raw = open(fp, "rb").read()
    try:
        t = raw.decode("utf-8")
    except UnicodeDecodeError:
        continue                      # binary asset, leave it alone
    new, n = apply(t)
    if n:
        open(fp, "w", encoding="utf-8").write(new)
        changed += 1
        total += n
        print("%-72s %d" % (fp, n))

# stylesheet rule (idempotent, marker-delimited)
css_file = "site/local-copy.css"
t = open(css_file, encoding="utf-8").read()
if CSS_BEGIN in t and CSS_END in t:
    a, b = t.index(CSS_BEGIN), t.index(CSS_END) + len(CSS_END)
    t = t[:a] + CSS.strip() + t[b:]
else:
    t = t.rstrip() + "\n\n" + CSS
open(css_file, "w", encoding="utf-8").write(t)
print("stylesheet:", css_file)

left = []
for fp in walk():
    try:
        t = open(fp, encoding="utf-8").read()
    except (UnicodeDecodeError, OSError):
        continue
    # Case sensitive on purpose: lowercase "jesper..." belongs to URLs,
    # social handles and the email address, which must stay untouched.
    if re.search(r"Jesper\s+Landberg|\bJesper\b|\bLandberg\b", t):
        left.append(fp)
print("\nfiles changed: %d | replacements: %d | brand: %s" % (changed, total, BRAND))
print("remaining old-name files:", left)
if left:
    raise SystemExit(1)
